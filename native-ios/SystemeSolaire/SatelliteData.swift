// Lancements de repli (fenêtres illustratives), remplacés par l'API Launch Library quand elle répond
struct LaunchSpec: Identifiable, Equatable {
    var id: String { n + (iso ?? "") }
    let n: String
    let meta: String
    var detail: String = ""
    let lat: Double
    let lon: Double
    var iso: String? = nil
    var offsetHours: Double? = nil
    var status: String = ""
    let color: UInt32
    var date: Date {
        if let iso, let d = ISO8601DateFormatter().date(from: iso) { return d }
        return Date().addingTimeInterval((offsetHours ?? 0) * 3600)
    }
    static func == (a: LaunchSpec, b: LaunchSpec) -> Bool { a.id == b.id }
}

